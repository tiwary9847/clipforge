  <ol>
    <li>Put the long video on the timeline.</li>
    <li>Tools → <b>Long video → Shorts</b>: 5 Shorts, 30–45 s → Find the best moments.</li>
    <li>Open each moment, add captions (Word highlight) and a hook title, or press Export all if you’re in a hurry.</li>
    <li>Tip: Tools → <b>Edit by text</b> removes “um / matlab / basically” and long pauses first.</li>
  </ol>
